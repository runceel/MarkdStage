test("every skill exposes Archify imports and the canonical guidance", async () => {
  for (const target of Object.keys(SKILL_TARGETS)) {
    const files = await buildSkillFiles(target);
    const skill = files.get("SKILL.md");
    assert.match(skill, /import an Archify SVG/);
    assert.match(skill, /```archify\nassets\/checkout-architecture\.svg\n```/);
    assert.match(skill, /markdstage guide slide-format/);
    assert.match(skill, /Architecture Editor does not edit imported SVGs/);
    assert.match(files.get("references/overview.md"), /`archify` fence/);
    assert.match(files.get("references/slide-format.md"), /```archify\nassets\//);
  }

  const canvasSkill = (await buildSkillFiles("copilot")).get("SKILL.md");
  assert.match(canvasSkill, /import an Archify SVG/);
  assert.match(canvasSkill, /```archify\nassets\/checkout-architecture\.svg\n```/);
  assert.match(canvasSkill, /pass every slide to the `open` input/);
  assert.match(canvasSkill, /markdstage guide slide-format/);
});

test("generated skills teach the diagnostic-first authoring loop", async () => {
  const skill = (await buildSkillFiles("codex")).get("SKILL.md");
  const stages = [
    "markdstage guide slide-format",
    "markdstage validate slides.md --json",
    "markdstage slides.md",
    "markdstage inspect slides.md --json",
    "markdstage capture slides.md",
    "markdstage present slides.md",
    "markdstage export slides.md --output slides.pdf",
    "markdstage export slides.md --output slides.pptx",
  ];
  let previous = -1;
  for (const stage of stages) {
    const index = skill.indexOf(stage);
    assert.ok(index > previous, `${stage} must appear in workflow order`);
    previous = index;
  }
  assert.match(skill, /captures only clipped slides/);
  assert.match(skill, /Prefer structured validation\s+and layout diagnostics over capturing every slide/);
});

test("generation is deterministic", async () => {
  const first = await buildSkillFiles("codex");
  const second = await buildSkillFiles("codex");
  assert.deepEqual([...first.entries()], [...second.entries()]);
});

test("install does not overwrite user-modified files without --force", async () => {
  const dir = await mkdtemp(join(tmpdir(), "markdstage-skill-"));
  try {
    await skillCommand({ action: "install", target: "codex", root: dir });
    const skillFile = join(dir, ...SKILL_TARGETS.codex.directory, "SKILL.md");
    await writeFile(skillFile, "# edited by the user\n", "utf8");

    const report = await skillCommand({ action: "install", target: "codex", root: dir });
    assert.equal(report.conflicts, 1);
    assert.equal(await readFile(skillFile, "utf8"), "# edited by the user\n");

    const forced = await skillCommand({
      action: "install",
      target: "codex",
      root: dir,
      force: true,
    });
    assert.equal(forced.conflicts, 0);
    assert.notEqual(await readFile(skillFile, "utf8"), "# edited by the user\n");
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test("check never writes files", async () => {
  const dir = await mkdtemp(join(tmpdir(), "markdstage-skill-check-"));
  try {
    const report = await skillCommand({ action: "check", target: "claude", root: dir });
    assert.ok(report.changed > 0);
    await assert.rejects(
      readFile(join(dir, ...SKILL_TARGETS.claude.directory, "SKILL.md"), "utf8"),
    );
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test("unknown targets and actions are rejected", async () => {
  await assert.rejects(skillCommand({ target: "emacs" }), /Unknown skill target/);
  await assert.rejects(skillCommand({ action: "remove" }), /Unknown skill action/);
});
